import fs from "node:fs";
import path from "node:path";
import { migrate } from "drizzle-orm/better-sqlite3/migrator";
import type { Db, Sqlite } from "./client";

/** One entry of drizzle/meta/_journal.json. Drizzle records `when` as `__drizzle_migrations.created_at`. */
export interface MigrationJournalEntry {
  idx: number;
  tag: string;
  when: number;
}

/** The migrations this app ships with (drizzle/meta/_journal.json in `migrationsFolder`), oldest first. */
export function readMigrationJournal(migrationsFolder: string): MigrationJournalEntry[] {
  const file = path.join(migrationsFolder, "meta", "_journal.json");
  const journal = JSON.parse(fs.readFileSync(file, "utf8")) as { entries?: unknown };
  if (!Array.isArray(journal.entries)) throw new Error(`Invalid migration journal: ${file}`);
  return journal.entries
    .map((e: { idx?: unknown; tag?: unknown; when?: unknown }) => {
      if (typeof e?.when !== "number" || !Number.isFinite(e.when) || typeof e.tag !== "string") {
        throw new Error(`Invalid migration journal entry in ${file}: ${JSON.stringify(e)}`);
      }
      return { idx: Number(e.idx), tag: e.tag, when: e.when };
    })
    .sort((a, b) => a.when - b.when);
}

export interface SchemaVersionCheck {
  /** Migrations recorded in the database (0 for a fresh / non-drizzle database). */
  applied: number;
  /** App migrations the next `runMigrations` would apply (same rule as drizzle: `when` > newest applied). */
  pending: number;
  /**
   * `created_at` of applied migrations this app does not ship. Drizzle only ever records a journal `when`, so these
   * come from another (in practice newer) build of the app, whose schema this build does not know.
   */
  unknown: number[];
  /** True when `unknown` is non-empty (and not `legacy`): this app must not open / migrate / restore this database. */
  newerThanApp: boolean;
  /**
   * The database comes from a pre-release test build (the migrations before 0.1.0 were squashed into 0000_init):
   * every applied migration is older than this app's first one. Its data is not carried over.
   */
  legacy: boolean;
}

/**
 * Compares the migrations applied to `sqlite` with the app's journal. Read-only (works on a readonly handle).
 * Drizzle's migrator alone is not enough: it applies app migrations newer than the newest applied one, so on a
 * database from a newer app it silently applies nothing and the app would run on a schema it does not know.
 */
export function checkSchemaVersion(sqlite: Sqlite, journal: MigrationJournalEntry[] | string): SchemaVersionCheck {
  const entries = typeof journal === "string" ? readMigrationJournal(journal) : journal;
  const hasTable = !!sqlite.prepare("SELECT 1 FROM sqlite_master WHERE type = 'table' AND name = '__drizzle_migrations'").get();
  const applied = hasTable
    ? (sqlite.prepare("SELECT created_at FROM __drizzle_migrations").pluck().all() as unknown[]).map((v) => Number(v))
    : [];
  const known = new Set(entries.map((e) => e.when));
  const unknown = applied.filter((t) => !known.has(t)).sort((a, b) => a - b);
  const newestApplied = applied.length ? Math.max(...applied) : -Infinity;
  const firstWhen = entries.length ? Math.min(...entries.map((e) => e.when)) : Infinity;
  const legacy = applied.length > 0 && applied.every((t) => t < firstWhen);
  return {
    applied: applied.length,
    pending: entries.filter((e) => e.when > newestApplied).length,
    unknown,
    newerThanApp: unknown.length > 0 && !legacy,
    legacy,
  };
}

/** Thrown by `runMigrations` when the database was already migrated by a newer app version. */
export class SchemaNewerThanAppError extends Error {
  constructor(public check: SchemaVersionCheck) {
    super(`Database has ${check.unknown.length} migration(s) unknown to this app version (created_at ${check.unknown.join(", ")})`);
    this.name = "SchemaNewerThanAppError";
  }
}

/** Thrown by `runMigrations` for a database of a pre-release test build (see SchemaVersionCheck.legacy). */
export class LegacyDatabaseError extends Error {
  constructor(public check: SchemaVersionCheck) {
    super(`Database is from a pre-release test build (${check.applied} old migration(s)); it is not carried over`);
    this.name = "LegacyDatabaseError";
  }
}

/**
 * Applies pending SQL migrations from the /drizzle folder (generated by `npm run db:generate`).
 * Throws (before touching the database) SchemaNewerThanAppError when it was migrated by a newer app version, and
 * LegacyDatabaseError when it comes from a pre-release test build.
 */
export function runMigrations(db: Db, migrationsFolder: string): void {
  // drizzle() sets $client (the better-sqlite3 handle); the Db alias in ./client just does not declare it.
  const check = checkSchemaVersion((db as Db & { $client: Sqlite }).$client, migrationsFolder);
  if (check.legacy) throw new LegacyDatabaseError(check);
  if (check.newerThanApp) throw new SchemaNewerThanAppError(check);
  migrate(db, { migrationsFolder });
}
